/**
 * RESEARCH ONLY / NOT PRODUCTION / NOT CANONICAL
 *
 * Turns the result files into the tables a person reads.
 *
 * Every number in results/SUMMARY.md is copied by this script from a JSON file
 * a benchmark wrote. Nothing in it was typed by hand, so the tables cannot
 * disagree with the measurements they report -- and a table that looks wrong
 * can be traced to one field of one file.
 *
 * Run: node research/m7-drawing-set-manager/benchmark/summarise.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const RESULTS = path.join(path.dirname(fileURLToPath(import.meta.url)), 'results');
const load = (name) => JSON.parse(fs.readFileSync(path.join(RESULTS, name), 'utf8'));

const fp = load('fingerprint-browser.json');
const extra = load('fingerprint-browser-extra.json');
const fpNode = load('fingerprint-node.json');
const probes = load('browser-probes.json');
const scaleNode = load('scale-node.json');
const scaleBrowser = load('scale-browser.json');
const hostile = load('hostile-node.json');

const lines = [];
const out = (text = '') => lines.push(text);
const table = (head, rows) => {
    out(`| ${head.join(' | ')} |`);
    out(`|${head.map(() => '---').join('|')}|`);
    for (const row of rows) out(`| ${row.join(' | ')} |`);
    out();
};
const kib = (bytes) => `${(bytes / 1024).toFixed(0)} KiB`;
const mib = (bytes) => `${(bytes / 1024 / 1024).toFixed(2)} MiB`;

out('# Benchmark summary');
out();
out('> **RESEARCH ONLY / NOT PRODUCTION / NOT CANONICAL.** Synthetic data only.');
out('> Generated by `benchmark/summarise.mjs` from the JSON files in this directory. Do not edit by hand.');
out('> **Browser** and **Node** figures are in separate sections and are never mixed in one table.');
out();
out(`- Browser: \`${fp.environment.browserVersion}\` (Chrome for Testing, headless), ${fp.machine.platform}, ${fp.machine.cpu}, ${fp.machine.logicalCpus} logical CPUs, ${fp.machine.totalMemoryGiB} GiB RAM (${fp.machine.freeMemoryGiBAtStart} GiB free at start).`);
out(`- Node: \`${scaleNode.environment.node}\` (V8 ${scaleNode.environment.v8}), same machine.`);
out('- Times are milliseconds, medians. Memory is the peak the operating system reported for the Chrome renderer process, one fresh browser per run.');
out();

// ---------------------------------------------------------------------------
out('## 1. Source fingerprint — BROWSER');
out();
out(`Baseline — a page with a 250 MiB file selected and not read: renderer peak working set **${fp.baselineLargestFileSelectedNotRead.rendererPeakWorkingSetMiB} MiB**, commit ${fp.baselineLargestFileSelectedNotRead.rendererPeakCommitMiB} MiB.`);
out();
out('### 1.1 One file');
out();
for (const [key, text] of Object.entries(fp.methods)) out(`- \`${key}\` — ${text}`);
out();
table(['Size', 'Method', 'Total ms', 'MiB/s', 'Longest page-thread gap ms', 'Renderer peak working set MiB', 'Renderer peak commit MiB'],
    fp.singleFile.map((r) => [`${r.sizeMiB} MiB`, `\`${r.method}\``, r.medianMs, r.MiBPerSecond, r.maxMainThreadGapMs, r.rendererPeakWorkingSetMiB, r.rendererPeakCommitMiB]));

out('### 1.2 Where the one-shot method spends its time, and what it blocks');
out();
out('`file.arrayBuffer()` and `crypto.subtle.digest()` on the page thread, each under its own heartbeat.');
out();
table(['Size', '`file.arrayBuffer()` ms', 'page-thread gap during read ms', '`subtle.digest()` ms', 'page-thread gap during digest ms'],
    extra.oneShotPageThreadSplit.runs.map((r) => [`${r.sizeMiB} MiB`, r.fileArrayBuffer.ms, r.fileArrayBuffer.mainThread.maxGapMs, r.subtleDigest.ms, r.subtleDigest.mainThread.maxGapMs]));

out('### 1.3 Chunk size for the streaming method (100 MiB file, `stream-worker`)');
out();
table(['Chunk', 'Total ms', 'MiB/s', 'Renderer peak working set MiB'], fp.chunkSize.map((r) => [kib(r.chunkKiB * 1024), r.medianMs, r.MiBPerSecond, r.rendererPeakWorkingSetMiB]));

out('### 1.4 Streaming with a new buffer per chunk vs one reused buffer');
out();
for (const [key, text] of Object.entries(extra.methods)) out(`- \`${key}\` — ${text}`);
out();
table(['Size', 'Method', 'Total ms', 'MiB/s', 'Renderer peak working set MiB', 'Renderer peak commit MiB'],
    extra.singleFile.map((r) => [`${r.sizeMiB} MiB`, `\`${r.method}\``, r.medianMs, r.MiBPerSecond, r.rendererPeakWorkingSetMiB, r.rendererPeakCommitMiB]));

out('### 1.5 Several files, strictly one after another');
out();
table(['Files', 'Method', 'Total ms', 'MiB/s', 'Longest page-thread gap ms', 'Renderer peak working set MiB', 'Renderer peak commit MiB'],
    [...fp.multiFileSequential, ...extra.multiFileSequential.filter((r) => r.method === 'byob-worker')]
        .map((r) => [`${r.files} × ${r.eachMiB} MiB`, `\`${r.method}\``, r.medianMs, r.MiBPerSecond, r.maxMainThreadGapMs, r.rendererPeakWorkingSetMiB, r.rendererPeakCommitMiB]));

out('### 1.6 Cancellation (250 MiB file)');
out();
table(['Method', 'Chunk', 'Asked to stop after ms', 'Outcome', 'Time from request to stopped ms'],
    fp.cancellation.streamingCancelledAfter150Ms.map((r) => ['`stream-worker`', kib(r.chunkBytes), r.cancelAfterMs, r.outcome, r.cancelLatencyMs]));
const t = fp.cancellation.oneShotWorkerTerminatedAfter30Ms;
out(`One-shot in a Worker cannot be interrupted; the Worker is terminated instead: \`terminate()\` returned in ${t.terminateCallMs} ms, no result was delivered (${t.resultDelivered}), and a fresh Worker answered in ${t.freshWorkerReadyMs} ms.`);
out();

// ---------------------------------------------------------------------------
out('## 2. SHA-256 implementations — NODE');
out();
out('Hash throughput on this CPU with file reading removed or done by Node. Not a statement about a browser.');
out();
table(['Size', 'native stream (OpenSSL) ms', 'Web Crypto one-shot ms', 'JS incremental (in memory) ms', 'MiB/s', 'JS one-shot, Production `digest.ts` ms', 'MiB/s', 'JS incremental from Blob slices ms'],
    fpNode.rows.map((r) => [`${r.sizeMiB} MiB`, r.nativeStream.ms, r.webcryptoOneShot.ms, r.jsIncrementalInMemory.ms, r.jsIncrementalInMemory.MiBPerSecond, r.jsOneShotProductionDigestTs.ms, r.jsOneShotProductionDigestTs.MiBPerSecond, r.jsIncrementalFromBlob.ms]));
out('All five implementations produced the same digest for every file.');
out();

// ---------------------------------------------------------------------------
out('## 3. Facts observed in the browser — BROWSER');
out();
const s = probes.secureContext.env;
const i = probes.insecureContext.env;
table(['', `Secure context (\`${s.origin}\`)`, `Insecure context (\`${i.origin}\`)`], [
    ['`isSecureContext`', s.isSecureContext, i.isSecureContext],
    ['`crypto.subtle.digest`', s.cryptoSubtleDigest, i.cryptoSubtleDigest],
    ['`crypto.randomUUID`', s.cryptoRandomUUID, i.cryptoRandomUUID],
    ['`crypto.getRandomValues`', s.cryptoGetRandomValues, i.cryptoGetRandomValues],
    ['`Worker`', s.worker, i.worker],
    ['`crypto.subtle` inside a Worker', probes.secureContext.worker.subtle, probes.insecureContext.worker.subtle],
    ['`Blob.prototype.stream`', s.blobStream, i.blobStream],
    ['`showOpenFilePicker`', s.showOpenFilePicker, i.showOpenFilePicker],
]);
out(`Insecure context reached as: ${probes.insecureContext.how}.`);
out();
table(['Fingerprint a 10 MiB file in the insecure context', 'Correct digest', 'Detail'],
    Object.entries(probes.insecureContext.fingerprint).map(([method, r]) => [`\`${method}\``, r.ok, r.error ?? (r.workerReply ? `worker replied \`${r.workerReply}\`, ${r.totalMs} ms` : `${r.totalMs} ms`)]));
const f = probes.secureContext.facts;
table(['Fact', 'Observed'], [
    ['`crypto.subtle.digest()` accepts a `ReadableStream`', `${f.subtleDigestAcceptsStream} (${f.subtleDigestStreamError})`],
    ['`byteLength` of an ArrayBuffer after it is transferred away', f.detachedBuffer.byteLengthAfterTransfer],
    ['digest of that detached buffer equals the digest of zero bytes', f.detachedBuffer.digestAfterIsEmptyDigest],
    ['`digest()` leaves its input buffer usable', f.digestLeavesInputUsable],
    [`structured clone of a ${mib(f.fileCloneBytes)} \`File\` to a Worker`, `${f.fileCloneToWorkerMs} ms`],
    ['a version-4 UUID built from `getRandomValues`', f.uuidFromGetRandomValues],
]);
out('A file changed on disk after it was selected:');
out();
table(['Change', '`slice()`', '`arrayBuffer()`', 'streamed read'],
    Object.entries(probes.fileChangedOnDiskAfterSelection).map(([name, r]) => [name, r.afterChange.sliceError ?? `read ${r.afterChange.slice} bytes`, r.afterChange.wholeError ?? `read ${r.afterChange.whole} bytes`, r.afterChange.streamError ?? `read ${r.afterChange.streamed} bytes`]));

// ---------------------------------------------------------------------------
const scaleTable = (report) => {
    table(['Drawing Set', 'Sources', 'Findings', 'Decisions', 'File (compact)', 'Bytes / sheet', 'File (indented)', 'JSON values', 'Save ms', 'Open ms', 'decode', 'scan', 'JSON.parse', 'schema', 'relations'],
        report.rows.map((r) => [r.label, r.shape.sources, r.shape.findings, r.shape.decisions, mib(r.size.compactBytes), r.size.bytesPerSheet, mib(r.size.prettyBytes), r.size.jsonValues,
            r.save.exportTotal.medianMs, r.open.importTotal.medianMs, r.open.stageMedians.decodeMs, r.open.stageMedians.scanMs, r.open.stageMedians.parseMs, r.open.stageMedians.schemaMs, r.open.stageMedians.relationsMs]));
    table(['Drawing Set', 'QA: all rules ms', 'QA: evaluate + reconcile ms', 'duplicate-number detection ms', 'gap detection ms', 'list rows ms', 'sort by number ms', 'filter by text ms', 'filter needs-attention ms', 'currency of everything ms', 'Final readiness ms', 'after one Source replaced: stale sheets / findings'],
        report.rows.map((r) => [r.label, r.qa.evaluateAllRules.medianMs, r.qa.evaluateAndReconcileNoChange.medianMs, r.qa.duplicateNumberDetectionOnly.medianMs, r.qa.gapDetectionOnly.medianMs,
            r.list.buildRows.medianMs, r.list.sortByNumber.medianMs, r.list.filterByText.medianMs, r.list.filterNeedsAttention.medianMs, r.stale.currencyOfEverything.medianMs, r.stale.finalReadiness.medianMs,
            `${r.stale.afterOneSourceReplaced.staleSheets} of ${r.stale.afterOneSourceReplaced.totalSheets} / ${r.stale.afterOneSourceReplaced.staleFindings} of ${r.stale.afterOneSourceReplaced.totalFindings} (${r.stale.afterOneSourceReplaced.medianMs} ms)`]));
};
out('## 4. Portable state and QA engine at scale — BROWSER (page thread)');
out();
scaleTable(scaleBrowser);
out('## 5. Portable state and QA engine at scale — NODE');
out();
scaleTable(scaleNode);

// ---------------------------------------------------------------------------
out('## 6. Opening and saving on the page thread — BROWSER');
out();
table(['Sheets', 'File', 'Open ms', 'Longest page-thread gap ms', 'Save ms', 'Longest page-thread gap ms'],
    probes.projectOpenAndSaveOnPageThread.map((r) => [r.sheets, mib(r.bytes), r.open.ms, r.open.mainThread.maxGapMs, r.save.ms, r.save.mainThread.maxGapMs]));

out('## 7. Hostile input, bounded and unbounded — NODE');
out();
out('`bounded` is the real import pipeline with the candidate limits. `unbounded` is `JSON.parse` alone.');
out();
table(['Input', 'Size', 'Bounded: refused at', 'in ms', 'reached JSON.parse', 'Unbounded: JSON.parse', 'ms', 'heap retained MiB', 'heap per input MiB', 'a recursive walk of the result'],
    hostile.hostile.map((c) => [c.input, `${c.bounded.inputMiB} MiB`, `${c.bounded.stage} / \`${c.bounded.code}\``, c.bounded.refusedInMs, c.bounded.reachedJsonParse,
        c.unbounded.jsonParse, c.unbounded.parseMs, c.unbounded.retainedHeapMiB, `${c.unbounded.heapPerInputByte}×`, c.unbounded.recursiveWalk]));
out('The largest files the importer accepts (a valid 5000-sheet Project grown with maximum-length comments):');
out();
table(['File', 'Decisions', 'Verdict', 'Save ms', 'Open ms', 'decode / scan / parse / schema / relations ms', 'Heap retained by the opened Project MiB', 'Process peak RSS MiB'],
    hostile.largestAccepted.map((r) => [`${r.MiB} MiB`, r.decisions, r.status, r.exportMs, r.importMs, `${r.stages.decodeMs} / ${r.stages.scanMs} / ${r.stages.parseMs} / ${r.stages.schemaMs} / ${r.stages.relationsMs}`, r.retainedHeapMiB, r.peakRssMiB]));

out('## 8. `JSON.parse` without bounds — BROWSER');
out();
table(['Input', 'Size', 'JSON.parse', 'ms', 'JS heap growth MiB', 'a recursive walk of the result'],
    probes.jsonParseWithoutBounds.map((r) => [r.input, `${r.inputMiB} MiB`, r.jsonParse, r.parseMs, r.jsHeapGrowthMiB, r.recursiveWalk]));

out('## 9. An un-virtualised Sheet List, as a lower bound — BROWSER');
out();
out(`${probes.sheetListPlainDomLowerBound.note}.`);
out();
table(['Rows', 'DOM nodes', 'Build ms', 'First layout ms', 'Restyle every row ms', 'Edit one row ms'],
    probes.sheetListPlainDomLowerBound.rows.map((r) => [r.rows, r.domNodes, r.buildMs, r.layoutMs, r.restyleAllMs, r.editOneRowMs]));

fs.writeFileSync(path.join(RESULTS, 'SUMMARY.md'), `${lines.join('\n')}\n`);
console.log(`written: results/SUMMARY.md (${lines.length} lines)`);
